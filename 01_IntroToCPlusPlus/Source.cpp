#include<iostream>
using namespace std;

int main() 
{
	//  \n - new line
	//  \t - tabulation
	//  \\ - \some text\
	//  \' - 'some text'
	//  \" - "some text"

	cout << "Hello world!\n";
	cout << "\t\tHello world!\n";
	cout << "\t\t\tHello world!\n";
	cout << "\\Hello\nworld!\\\n";
	cout << "\'Hello world!\'\n";
	cout << "\"Hello world!\"\n";

	return 0;
}
